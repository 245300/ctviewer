/**
 * Third-person exploration: choose one of the imported Girls' Frontline 2
 * characters and walk around the city the garage stands in.
 *
 * All ten characters share one skinned rig (bone names and rest orientations
 * differ by less than a degree), so the fifteen Mixamo clips are baked once
 * into assets/characters/animations.glb and played on whichever character is
 * equipped.  Movement is driven by this controller; the clips themselves are
 * de-trended, so feet keep their stride without the character sliding away.
 */
import * as THREE from 'three';
import { GLTFLoader } from 'three/addons/loaders/GLTFLoader.js';
import { DRACOLoader } from 'three/addons/loaders/DRACOLoader.js';
import { adaptHipsClip, applyGroundLift } from './character-clips.js';

const WALK_SPEED = 1.75;
// Run at twice the original pace (was 4.4).  Jump height scales with the square
// of the take-off speed, so 1.5x the old 0.63 m apex needs sqrt(1.5) x the old
// 4.5 m/s; the flight time grows by the same root, which reads as a lighter,
// bouncier hop rather than a moon jump.
const RUN_SPEED = 8.8;
const PLAYER_RADIUS = 0.34;
const GRAVITY = 16;
const JUMP_SPEED = 4.5 * Math.sqrt(1.5);
const EYE_HEIGHT = 1.42;
const SPAWN = new THREE.Vector3(0, 0, 17);
const MAX_RADIUS = 296;

// Chinese labels for the fifteen clips in the shared library.
export const CLIP_LABELS = {
  Idle: '待机',
  Walking: '行走',
  Running: '奔跑',
  Jumping: '跳跃',
  'Breakdance Ending 1': '街舞 · 收尾',
  'Breakdance Freeze Var 3': '街舞 · 定格',
  'Butterfly Twirl': '蝶舞回旋',
  Capoeira: '卡波耶拉',
  'Fist Fight B': '格斗 · 连击',
  'Martelo 2': '巴西战舞 · 马丁内罗',
  'Roundhouse Kick': '回旋踢',
  'Shoved Reaction With Spin': '受击转身',
  'Stable Sword Inward Slash': '剑术 · 内斩',
  'Stand Up': '起身',
  'Standing Torch Melee Attack 01': '火炬近战',
};

/**
 * The walk controller's keyboard map, input bindings and proximity test live
 * below.  The only car interaction kept is boarding: walk up to the displayed
 * car, press E, and the driving mode takes over.
 */

export class CharacterMode {
  constructor(viewer) {
    this.viewer = viewer;
    this.scene = viewer.scene;
    this.renderer = viewer.renderer;
    this.camera = new THREE.PerspectiveCamera(46, 1, 0.05, 3000);
    this.catalog = null;
    this.clips = null;
    this.loaded = new Map();
    this.root = null;
    this.mixer = null;
    this.actions = null;
    this.currentAction = null;
    this.oneShot = null;
    this.oneShotName = '';
    this.preview = null;
    this.active = false;
    this.keys = new Set();
    this.pos = SPAWN.clone();
    this.velocityY = 0;
    this.grounded = true;
    this.yaw = Math.PI;
    this.camYaw = 0;
    this.camPitch = 0.18;
    this.camDist = 4.4;
    this.dragging = false;
    this.lastPointer = { x: 0, y: 0 };
    this._nearCar = false;
    this.onNearCarChange = null;
    this.onEnterCar = null;
    this.onToast = null;
    this._buildMarker();
    this._bindInput();
  }

  get loader() {
    if (!this._loader) {
      const draco = new DRACOLoader().setDecoderPath('./vendor/draco/');
      this._loader = new GLTFLoader().setDRACOLoader(draco);
    }
    return this._loader;
  }

  async loadCatalog() {
    if (this.catalog) return this.catalog;
    const [catalog, ground] = await Promise.all([
      fetch('./assets/characters/characters.json', { cache: 'no-cache' })
        .then((r) => (r.ok ? r.json() : Promise.reject(new Error('人物目录加载失败')))),
      // Optional: generated by tools/ground_bake.html. Without it every clip
      // still plays; only the lying poses (Stand Up) sit low.
      fetch('./assets/characters/ground.json', { cache: 'no-cache' })
        .then((r) => (r.ok ? r.json() : null))
        .catch(() => null),
    ]);
    this.catalog = catalog;
    this.ground = ground;
    return this.catalog;
  }

  async loadClips() {
    if (this.clips) return this.clips;
    const cat = await this.loadCatalog();
    const gltf = await this.loader.loadAsync(`./${cat.animationsUrl}`);
    this.clips = gltf.animations;
    return this.clips;
  }

  async equip(id) {
    const cat = await this.loadCatalog();
    await this.loadClips();
    const meta = cat.characters.find((c) => c.id === id);
    if (!meta) throw new Error(`没有这个人物：${id}`);
    if (this.currentId === id && this.root) return meta;

    if (this.root) {
      this.scene.remove(this.root);
      this.mixer?.stopAllAction();
    }
    let entry = this.loaded.get(id);
    if (!entry) {
      const gltf = await this.loader.loadAsync(`./${meta.url}`);
      const root = gltf.scene;
      root.name = `Character:${id}`;
      root.traverse((o) => {
        if (!o.isMesh) return;
        o.castShadow = false;
        o.receiveShadow = false;
        // Animated skinned bounds are computed from the bind pose; keep the
        // character from popping out when the camera gets close.
        o.frustumCulled = false;
        for (const m of [].concat(o.material || [])) {
          if (!m) continue;
          if ('envMapIntensity' in m) m.envMapIntensity = 0.9;
          m.needsUpdate = true;
        }
      });
      const mixer = new THREE.AnimationMixer(root);
      // The shared library is baked on the reference character's hips.  Every
      // other character is taller or shorter, so playing that track verbatim
      // drops the pelvis to the reference height and buries the feet 15-22 cm
      // in the ground.  Rebase (and rescale) the hips translation onto this
      // rig's own hip height instead.
      const hipsRest = root.getObjectByName('Hips')?.position.clone() || null;
      const actions = {};
      for (const clip of this.clips) {
        const adapted = adaptHipsClip(clip, meta.hipHeight, cat.refHipHeight, hipsRest);
        applyGroundLift(adapted, this.ground?.characters?.[id]?.[clip.name]);
        actions[clip.name] = mixer.clipAction(adapted);
      }
      mixer.addEventListener('finished', (e) => {
        if (this.mixer === mixer && e.action === this.oneShot) this._clearOneShot();
      });
      entry = { root, mixer, actions };
      this.loaded.set(id, entry);
    }
    this.root = entry.root;
    this.mixer = entry.mixer;
    this.actions = entry.actions;
    this.currentId = id;
    this.meta = meta;
    this.scene.add(this.root);
    this.root.position.copy(this.pos);
    this.root.rotation.y = this.yaw;
    this.currentAction = null;
    this.oneShot = null;
    this.preview = null;
    this._play('Idle');
    return meta;
  }

  async enter(id) {
    await this.equip(id);
    this.active = true;
    this.pos.copy(SPAWN);
    this.velocityY = 0;
    this.grounded = true;
    this.yaw = Math.PI;
    this.camYaw = 0;
    this.camPitch = 0.2;
    this.root.position.copy(this.pos);
    this.root.rotation.y = this.yaw;
    this.oneShot = null;
    this.oneShotName = '';
    this.preview = null;
    this._play('Idle');
    this.marker.visible = true;
    this.shadow.visible = true;
    this._syncCamera();
    this._resize();
    return this.meta;
  }

  exit() {
    this.active = false;
    this.keys.clear();
    this.dragging = false;
    this.marker.visible = false;
    this.shadow.visible = false;
    this.mixer?.stopAllAction();
    if (this.root) this.scene.remove(this.root);
    this.root = null;
    this.currentId = null;
  }

  respawn() {
    if (!this.root) return;
    this.pos.copy(SPAWN);
    this.velocityY = 0;
    this.grounded = true;
    this.yaw = Math.PI;
    this.camYaw = 0;
    this.root.position.copy(this.pos);
    this.root.rotation.set(0, this.yaw, 0);
    this._play('Idle');
  }

  /** Drop the character beside a car door (used when stepping out of a drive). */
  teleportTo(x, z, yaw = 0) {
    if (!this.root) return;
    this.pos.set(x, 0, z);
    this.velocityY = 0;
    this.grounded = true;
    this.yaw = yaw;
    this.camYaw = yaw + Math.PI;
    this.root.position.copy(this.pos);
    this.root.rotation.set(0, yaw, 0);
    this._play('Idle');
  }

  /** True when the character is within a few metres of the bay's car. */
  canEnterCar() {
    if (!this.root) return false;
    const box = this.viewer._modelBox;
    if (!box || box.isEmpty()) return false;
    const pad = 2.8;
    return this.pos.x > box.min.x - pad && this.pos.x < box.max.x + pad
      && this.pos.z > box.min.z - pad && this.pos.z < box.max.z + pad;
  }

  playAction(name) {
    if (!this.actions?.[name]) return false;
    if (name === 'Idle' || name === 'Walking' || name === 'Running') {
      this.oneShot = null;
      this.oneShotName = '';
      // Walking / Running chips preview the cycle in place; the controller
      // takes over again as soon as a movement key is pressed.
      this.preview = name === 'Idle' ? null : name;
      this._play(name, { loop: true });
      return true;
    }
    if (name === 'Jumping') {
      this._jump();
      return true;
    }
    const action = this.actions[name];
    this.preview = null;
    this.oneShot = action;
    this.oneShotName = name;
    this._play(name, { loop: false, fade: 0.18 });
    return true;
  }

  _jump() {
    if (!this.grounded) return;
    this.preview = null;
    this.velocityY = JUMP_SPEED;
    this.grounded = false;
    this.oneShot = this.actions.Jumping || null;
    this.oneShotName = 'Jumping';
    this._play('Jumping', { loop: false, fade: 0.12, timeScale: 1.35 });
  }

  _play(name, { loop = true, fade = 0.22, timeScale = 1 } = {}) {
    const next = this.actions?.[name];
    if (!next) return;
    if (this.currentAction === next) {
      next.timeScale = timeScale;
      return;
    }
    next.reset();
    next.setLoop(loop ? THREE.LoopRepeat : THREE.LoopOnce, loop ? Infinity : 1);
    next.clampWhenFinished = !loop;
    next.timeScale = timeScale;
    next.setEffectiveWeight(1);
    next.fadeIn(fade).play();
    if (this.currentAction) this.currentAction.fadeOut(fade);
    this.currentAction = next;
  }

  _buildMarker() {
    const group = new THREE.Group();
    group.name = 'CharacterSpawn';
    const ringMat = new THREE.MeshBasicMaterial({
      color: 0x64e2ff, transparent: true, opacity: 0.5,
      side: THREE.DoubleSide, depthWrite: false, toneMapped: false,
    });
    this.markerRingMat = ringMat;
    const ring = new THREE.Mesh(new THREE.RingGeometry(0.7, 0.78, 64), ringMat);
    ring.rotation.x = -Math.PI / 2;
    ring.position.y = 0.03;
    group.add(ring);
    const ring2 = new THREE.Mesh(new THREE.RingGeometry(1.05, 1.08, 64), ringMat.clone());
    ring2.material.opacity = 0.22;
    ring2.rotation.x = -Math.PI / 2;
    ring2.position.y = 0.028;
    group.add(ring2);
    const core = new THREE.Mesh(
      new THREE.CircleGeometry(0.7, 48),
      new THREE.MeshBasicMaterial({
        color: 0x1b6f8f, transparent: true, opacity: 0.12,
        depthWrite: false, side: THREE.DoubleSide,
      }),
    );
    core.rotation.x = -Math.PI / 2;
    core.position.y = 0.008;
    group.add(core);
    const beam = new THREE.Mesh(
      new THREE.CylinderGeometry(0.62, 0.72, 9, 40, 1, true),
      new THREE.MeshBasicMaterial({
        color: 0x64e2ff, transparent: true, opacity: 0.035,
        depthWrite: false, side: THREE.DoubleSide, blending: THREE.AdditiveBlending,
        toneMapped: false,
      }),
    );
    beam.position.y = 4.5;
    group.add(beam);
    this.markerBeam = beam;
    // A small floating label so the spawn point is unmistakable from a few
    // metres away (and still legible when the character is standing on it).
    const label = document.createElement('canvas');
    label.width = 256;
    label.height = 64;
    const ctx = label.getContext('2d');
    ctx.fillStyle = 'rgba(6, 16, 24, 0.78)';
    ctx.beginPath();
    ctx.roundRect(2, 6, 252, 52, 12);
    ctx.fill();
    ctx.strokeStyle = 'rgba(143, 232, 255, 0.55)';
    ctx.lineWidth = 2;
    ctx.stroke();
    ctx.fillStyle = '#a9f0ff';
    ctx.font = '600 26px "Hanken Grotesk", "Microsoft YaHei", sans-serif';
    ctx.textAlign = 'center';
    ctx.textBaseline = 'middle';
    ctx.fillText('出生点 · SPAWN', 128, 33);
    const tex = new THREE.CanvasTexture(label);
    tex.colorSpace = THREE.SRGBColorSpace;
    const sprite = new THREE.Sprite(new THREE.SpriteMaterial({
      map: tex, transparent: true, depthWrite: false, toneMapped: false,
    }));
    sprite.scale.set(1.9, 0.475, 1);
    sprite.position.y = 1.95;
    group.add(sprite);
    this.markerLabel = sprite;
    this.marker = group;
    group.position.copy(SPAWN);
    group.visible = false;
    this.scene.add(group);

    // A soft contact shadow keeps the character anchored to the ground.
    this.shadowMat = new THREE.MeshBasicMaterial({
      color: 0x000000, transparent: true, opacity: 0.26,
      depthWrite: false, side: THREE.DoubleSide,
    });
    this.shadow = new THREE.Mesh(new THREE.CircleGeometry(0.42, 32), this.shadowMat);
    this.shadow.rotation.x = -Math.PI / 2;
    this.shadow.position.set(SPAWN.x, 0.022, SPAWN.z);
    this.shadow.visible = false;
    this.scene.add(this.shadow);
  }

  _bindInput() {
    this._onKeyDown = (e) => {
      if (!this.active) return;
      if (e.target.matches?.('input, textarea')) return;
      // The character picker can be opened while exploring; it owns the
      // keyboard until it is dismissed (Esc closes it, not the mode).
      if (document.querySelector('#character-modal.show')) { this.keys.clear(); return; }
      const code = e.code;
      if (code === 'KeyE') { e.preventDefault(); this.onEnterCar?.(); return; }
      if (code === 'Space') { e.preventDefault(); this._jump(); return; }
      if (['KeyW', 'KeyA', 'KeyS', 'KeyD', 'ShiftLeft', 'ShiftRight', 'KeyR', 'Escape'].includes(code)) {
        if (code === 'Escape') { this.onExit?.(); return; }
        if (code === 'KeyR') { this.respawn(); return; }
        this.keys.add(code);
      }
    };
    this._onKeyUp = (e) => { this.keys.delete(e.code); };
    window.addEventListener('keydown', this._onKeyDown);
    window.addEventListener('keyup', this._onKeyUp);
    window.addEventListener('blur', () => this.keys.clear());

    const canvas = this.renderer.domElement;
    this._onPointerDown = (e) => {
      if (!this.active || e.button !== 0) return;
      this.dragging = true;
      this.lastPointer.x = e.clientX;
      this.lastPointer.y = e.clientY;
      canvas.setPointerCapture?.(e.pointerId);
      canvas.style.cursor = 'grabbing';
    };
    this._onPointerMove = (e) => {
      if (!this.active || !this.dragging) return;
      const dx = e.clientX - this.lastPointer.x;
      const dy = e.clientY - this.lastPointer.y;
      this.lastPointer.x = e.clientX;
      this.lastPointer.y = e.clientY;
      this.camYaw -= dx * 0.006;
      this.camPitch = Math.max(-0.15, Math.min(0.95, this.camPitch + dy * 0.004));
    };
    this._onPointerUp = (e) => {
      this.dragging = false;
      canvas.style.cursor = this.active ? 'grab' : '';
      canvas.releasePointerCapture?.(e.pointerId);
    };
    this._onWheel = (e) => {
      if (!this.active) return;
      e.preventDefault();
      this.camDist = Math.max(2.2, Math.min(8.5, this.camDist + Math.sign(e.deltaY) * 0.45));
    };
    canvas.addEventListener('pointerdown', this._onPointerDown);
    canvas.addEventListener('pointermove', this._onPointerMove);
    canvas.addEventListener('pointerup', this._onPointerUp);
    canvas.addEventListener('pointercancel', this._onPointerUp);
    canvas.addEventListener('wheel', this._onWheel, { passive: false });
  }

  _blocked(x, z) {
    if (Math.hypot(x, z) > MAX_RADIUS) return true;
    const room = this.viewer._garageRoom;
    if (room) {
      // The garage is open on two sides - the front (+Z, the plaza side) and
      // the left (+X) - so the character can walk in and out through either.
      // Only the two glazed walls (right -X and back -Z) are solid.
      const m = PLAYER_RADIUS + 0.25;
      const wall = 0.55;
      const inFootprint = x > room.min.x - m && x < room.max.x + m
        && z > room.min.z - m && z < room.max.z + m;
      if (inFootprint && (x < room.min.x + wall || z < room.min.z + wall)) return true;
    }
    const props = this.viewer._garagePropBoxes;
    if (props) {
      // Everything the workshop rows stand on: walk through the bay, not the
      // furniture.  A little extra clearance keeps the camera out of shelves.
      const pad = PLAYER_RADIUS * 0.5;
      for (const box of props) {
        if (x > box.minX - pad && x < box.maxX + pad
            && z > box.minZ - pad && z < box.maxZ + pad) return true;
      }
    }
    const car = this.viewer._modelBox;
    if (car && !car.isEmpty()) {
      // The car itself is solid too - walking into the bay should not mean
      // walking through the car.
      const inset = 0.12;
      if (x > car.min.x + inset && x < car.max.x - inset
          && z > car.min.z + inset && z < car.max.z - inset) return true;
    }
    return this.viewer.city?.isBlocked?.(x, z) || false;
  }

  _move(dx, dz) {
    const r = PLAYER_RADIUS;
    if (!this._blocked(this.pos.x + dx + Math.sign(dx) * r, this.pos.z)
        && !this._blocked(this.pos.x + dx, this.pos.z)) {
      this.pos.x += dx;
    }
    if (!this._blocked(this.pos.x, this.pos.z + dz + Math.sign(dz) * r)
        && !this._blocked(this.pos.x, this.pos.z + dz)) {
      this.pos.z += dz;
    }
  }

  update(dt) {
    if (!this.active || !this.root) return;
    const k = this.keys;
    const mx = (k.has('KeyD') ? 1 : 0) - (k.has('KeyA') ? 1 : 0);
    const mz = (k.has('KeyW') ? 1 : 0) - (k.has('KeyS') ? 1 : 0);
    const run = k.has('ShiftLeft') || k.has('ShiftRight');
    const moving = mx !== 0 || mz !== 0;
    const fwd = new THREE.Vector3(-Math.sin(this.camYaw), 0, -Math.cos(this.camYaw));
    const right = new THREE.Vector3(Math.cos(this.camYaw), 0, -Math.sin(this.camYaw));
    const dir = new THREE.Vector3().addScaledVector(fwd, mz).addScaledVector(right, mx);
    if (dir.lengthSq() > 0) dir.normalize();

    const speed = moving ? (run ? RUN_SPEED : WALK_SPEED) : 0;
    if (moving) {
      this.preview = null;
      const targetYaw = Math.atan2(dir.x, dir.z);
      let diff = targetYaw - this.yaw;
      while (diff > Math.PI) diff -= Math.PI * 2;
      while (diff < -Math.PI) diff += Math.PI * 2;
      this.yaw += diff * Math.min(1, dt * 12);
      if (this.oneShot && this.oneShotName !== 'Jumping') this._clearOneShot();
    }

    // Physics runs in fixed sub-steps.  A single Euler step at the frame time
    // loses height on a slow frame (apex = v^2/2g - v*dt/2), which made a
    // 1.5x jump measure only 1.29x on a 17 fps machine.  The step is short
    // enough that the walk collision cannot tunnel either.
    let remaining = dt;
    while (remaining > 1e-6) {
      const step = Math.min(remaining, 1 / 120);
      remaining -= step;
      if (moving) this._move(dir.x * speed * step, dir.z * speed * step);
      // Vertical motion: a simple ballistic hop; the clip supplies the pose.
      if (!this.grounded) {
        this.velocityY -= GRAVITY * step;
        this.pos.y += this.velocityY * step;
        if (this.pos.y <= 0) {
          this.pos.y = 0;
          this.velocityY = 0;
          this.grounded = true;
          if (this.oneShotName === 'Jumping') this._clearOneShot();
        }
      }
    }

    this.root.position.copy(this.pos);
    this.root.rotation.y = this.yaw;
    this.shadow.position.set(this.pos.x, 0.022, this.pos.z);
    this.shadow.scale.setScalar(1 + this.pos.y * 0.28);
    this.shadowMat.opacity = 0.26 * Math.max(0.25, 1 - this.pos.y * 0.4);

    if (!this.oneShot && !this.preview) {
      // Threshold between the walk and run cycles: above the walk speed, well
      // below the run speed.  It used to be a fraction of RUN_SPEED, which
      // stopped matching once the run was doubled.
      if (speed > (WALK_SPEED + RUN_SPEED) / 2) this._play('Running', { timeScale: speed / RUN_SPEED });
      else if (speed > 0.1) this._play('Walking', { timeScale: speed / WALK_SPEED });
      else this._play('Idle');
    }

    this.mixer?.update(dt);
    this._updateMarker(dt);
    this._syncCamera();

    // The "press E" hint follows proximity with a small hysteresis-free check;
    // its only cost is one AABB expand per frame.
    const near = this.canEnterCar();
    if (near !== this._nearCar) {
      this._nearCar = near;
      this.onNearCarChange?.(near);
    }
  }

  _clearOneShot() {
    this.oneShot = null;
    this.oneShotName = '';
    this._play('Idle', { fade: 0.24 });
  }

  _updateMarker(dt) {
    const t = performance.now() * 0.001;
    this.markerRingMat.opacity = 0.42 + 0.2 * (0.5 + 0.5 * Math.sin(t * 2.1));
    this.markerBeam.material.opacity = 0.05 + 0.03 * (0.5 + 0.5 * Math.sin(t * 1.7));
    this.marker.rotation.y = t * 0.4;
  }

  _syncCamera() {
    const target = new THREE.Vector3(this.pos.x, this.pos.y + EYE_HEIGHT * 0.82, this.pos.z);
    const cp = Math.cos(this.camPitch);
    const cam = new THREE.Vector3(
      this.pos.x + Math.sin(this.camYaw) * this.camDist * cp,
      this.pos.y + 1.35 + Math.sin(this.camPitch) * this.camDist,
      this.pos.z + Math.cos(this.camYaw) * this.camDist * cp,
    );
    cam.y = Math.max(0.45, cam.y);
    const room = this.viewer._garageRoom;
    if (room) {
      for (let i = 0; i < 14; i++) {
        const m = 0.3;
        if (cam.x < room.min.x - m || cam.x > room.max.x + m
            || cam.z < room.min.z - m || cam.z > room.max.z + m
            || cam.y < -0.5 || cam.y > room.max.y + m) break;
        cam.lerp(target, 0.12);
      }
    }
    this.camera.position.copy(cam);
    this.camera.lookAt(target);
  }

  onResize() {
    if (!this.active) return;
    this._resize();
  }

  _resize() {
    const size = this.renderer.getSize(new THREE.Vector2());
    this.camera.aspect = size.x / Math.max(1, size.y);
    this.camera.updateProjectionMatrix();
  }
}
